CATEGORIES = {
    "net_hot": NET_HOT,
    "daily_chat": DAILY_CHAT,
    "media": MEDIA,
    "ai_term": AI_TERM,
}

def main():
    total = 0
    for name, blob in CATEGORIES.items():
        words = blob.split()
        seen, kept, dropped = set(), [], []
        for w in words:
            if not w or w in seen:
                continue
            seen.add(w)
            if not WORD_OK.match(w):
                dropped.append(w)
                continue
            py = " ".join(lazy_pinyin(w))
            kept.append((w, py))
        if dropped:
            with io.open(os.path.join(DOCS, "%s_dropped.txt" % name), "w", encoding="utf-8", newline="\n") as fd:
                fd.write("\n".join(dropped) + "\n")
        out = os.path.join(DOCS, "%s_ime_dict.txt" % name)
        with io.open(out, "w", encoding="utf-8", newline="\n") as f:
            for w, py in kept:
                f.write("%s %s\n" % (w, py))
        total += len(kept)
        print("%-12s 保留 %4d 条  丢弃 %2d 条  -> %s" % (name, len(kept), len(dropped), os.path.basename(out)))
        if dropped:
            print("             丢弃示例: %s" % "、".join(dropped[:8]))
    print("合计 %d 条" % total)

if __name__ == "__main__":
    main()
